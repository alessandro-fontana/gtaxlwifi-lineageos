// bootsplash — the animation that fills the black gap between the kernel and
// the LineageOS bootanimation (§43).
//
// The black gap, measured on the tablet: from 1.171 s — when exynos-drm binds
// the DECON and the scanout inherited from the bootloader stops — until
// 20.8 s, when SurfaceFlinger does its modeset and the bootanimation starts.
// Twenty seconds in which the panel is on and shows nothing (§25.1).
//
// This program draws the LineageOS animation — three rotating dots — at the
// same position and with the same frames as the bootanimation. The image is
// in `anim.rle`, generated by `tools/make-bootsplash-anim.py` from the
// build's bootanimation, and linked into the binary with .incbin.
//
// Constraints from which everything else follows:
//
//  - It runs in FIRST STAGE, inside the ramdisk, before SwitchRoot. After the
//    switch its "/" is the old root and /dev has been moved: so the program
//    waits for and opens the DRM card BEFORE notifying generic_init through
//    --ready-fd, and from then on it no longer touches the filesystem. No
//    dynamic libraries (static binary), no libpng, no libz.
//
//  - After the modeset it drops master (DROP_MASTER). Scanout continues —
//    the CRTC is not turned off — but SurfaceFlinger can take the display
//    when it arrives, without finding the door locked. The animation goes on
//    by writing into the mapped buffer, which does not require being master.
//
//  - SELinux switches to enforcing while the process is alive (init second
//    stage). The process stays in the `kernel` domain, so after the modeset
//    it makes no call that the policy would have to allow: only writes to
//    already-mapped memory and clock_nanosleep. /dev/kmsg is also closed
//    before the loop.
//
// It runs at two different times:
//
//  - at boot, launched by generic_init in first stage (the main case);
//  - when leaving charging mode, when the key is pressed to continue into
//    Android: there the kernel has been up for a while, the charger releases
//    the display and nobody draws anything until SurfaceFlinger. init
//    restarts it on `sys.boot_from_charger_mode=1`, as a vendor service with
//    its own domain (§43.11).
//
// Outside of boot it can be tried by hand, as was done for the charger in
// §30.6:
//
//     adb push out/.../ramdisk/system/bin/bootsplash /vendor/bin/   # overlay rw
//     adb shell setprop ctl.stop surfaceflinger
//     adb shell /vendor/bin/bootsplash --seconds=15
//     adb shell setprop ctl.start surfaceflinger

